/**
 * Picks the fixed campaign levels and writes them to src/game/levels.data.ts.
 *
 * The levels are committed data, not generated at runtime, so they stay the
 * same even if the generator is retuned later. Re-running this script after
 * such a change produces a different campaign; players keep their progress
 * by level number, not by puzzle.
 */
import { writeFileSync } from 'node:fs';
import { generatePuzzle, patternKey, type Difficulty, type Puzzle } from '../src/engine/index.ts';

const POOL = 3000;
const PER_TIER = 10;

function signature(p: Puzzle): string {
  return JSON.stringify([p.gridSize, p.folds, p.punches]);
}

/** Every distinct puzzle of a difficulty, easiest first. */
function pool(difficulty: Difficulty): Puzzle[] {
  const seenPuzzles = new Set<string>();
  const seenAnswers = new Set<string>();
  const out: Puzzle[] = [];
  for (let seed = 0; seed < POOL; seed++) {
    const puzzle = generatePuzzle(seed, difficulty);
    const answer = patternKey(puzzle.options[puzzle.correctIndex]!);
    if (seenPuzzles.has(signature(puzzle)) || seenAnswers.has(answer)) continue;
    seenPuzzles.add(signature(puzzle));
    seenAnswers.add(answer);
    out.push(puzzle);
  }
  return out.sort((a, b) => a.rating - b.rating || a.seed - b.seed);
}

/** `count` puzzles spread evenly from the easiest to the hardest. */
function spread(sorted: readonly Puzzle[], count: number): Puzzle[] {
  if (sorted.length < count) throw new Error(`Need ${count} puzzles, only have ${sorted.length}`);
  return Array.from({ length: count }, (_, i) => sorted[Math.round((i * (sorted.length - 1)) / (count - 1))]!);
}

const easy = pool('easy');
const medium = pool('medium');
const hard = pool('hard');

const levels = [
  // Tiers 1–2: a few single folds to learn the idea, then two folds on a 4×4 sheet.
  ...spread(easy.filter((p) => p.folds.length === 1), 4),
  ...spread(easy.filter((p) => p.folds.length === 2), PER_TIER * 2 - 4),
  // Tiers 3–4: a 6×6 sheet, diagonals and second punches.
  ...spread(medium, PER_TIER * 2),
  // Tier 5: everything at once.
  ...spread(hard, PER_TIER),
].map((puzzle, index): Puzzle => ({ ...puzzle, id: `level-${index}` }));

const lines = levels.map((level) => `  ${JSON.stringify(level)},`).join('\n');
writeFileSync(
  new URL('../src/game/levels.data.ts', import.meta.url),
  `// Generated by \`npm run levels\` (scripts/generate-levels.ts). Do not edit by hand.
import type { Puzzle } from '../engine/index.ts';

export const LEVEL_DATA: readonly Puzzle[] = [
${lines}
];
`,
);

for (let tier = 0; tier < levels.length / PER_TIER; tier++) {
  const row = levels.slice(tier * PER_TIER, (tier + 1) * PER_TIER);
  console.log(
    `tier ${tier + 1}:`,
    row.map((p) => `${p.folds.length}f/${p.punches.length}p/${p.options[p.correctIndex]!.length}h@${p.rating}`).join('  '),
  );
}
console.log('answers:', levels.map((p) => 'ABCD'[p.correctIndex]).join(''));
